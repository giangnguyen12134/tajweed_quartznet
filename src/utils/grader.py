"""
Tajweed grader -- turns a CTC forced alignment into per-rule verdicts.

Rule identity now comes from quranic-phonemizer's own 44-rule catalogue
(RuleSpan.rule values are the library's rule_id strings, e.g. "madd_tabii",
"idgham_mutaqaribayn", "ikhfaa_shafawi" -- see assets/rule_catalogue.json,
generated by scripts/build_vocab.py, or `Phonemizer().tajweed_rules`). This
module owns three things the library deliberately does NOT provide, because
they are grading pedagogy rather than phonetic analysis:

  1. NOMINAL_HARAKAT -- how many harakat a correct recitation of each
     duration-graded rule should occupy. The library tells us WHICH rule
     fired and WHICH tokens realise it; the 2/4/6-harakat madd convention
     (and Hafs-via-Shatibiyyah's tolerance of 4 OR 5 for muttasil/munfasil)
     is pedagogy layered on top, and belongs here, not in the phonemizer.
  2. TOLERANCE -- how far a measured duration can drift from nominal before
     it counts as an error, expressed as a ratio (never milliseconds --
     see estimate_harakah_ms below for why).
  3. SEVERITY -- which errors matter more when computing an overall score.

HUMAN (display names) IS pulled from the library's own catalogue rather than
hand-typed, via assets/rule_catalogue.json -- one less place for the rule
list and the tables to silently drift out of sync with each other.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

FRAME_MS = 20.0        # encoder frame rate (50 fps)

# Verdict classes emitted by the learned verifier head.
CLASSES = ["correct", "too_short", "too_long", "missing",
           "substituted", "no_ghunnah", "weak_articulation", "inserted"]

# ---------------------------------------------------------------------------
# Rule catalogue (display names), loaded from the derived asset
# ---------------------------------------------------------------------------
_CATALOGUE_PATH = Path(__file__).resolve().parents[2] / "assets" / "rule_catalogue.json"


def _load_human_names() -> Dict[str, str]:
    if _CATALOGUE_PATH.exists():
        rules = json.loads(_CATALOGUE_PATH.read_text(encoding="utf-8"))
        return {r["id"]: r["name"] for r in rules}
    return {}


HUMAN: Dict[str, str] = _load_human_names()


def human_name(rule_id: str) -> str:
    return HUMAN.get(rule_id, rule_id.replace("_", " "))


# ---------------------------------------------------------------------------
# Grading pedagogy -- ours, not the library's
# ---------------------------------------------------------------------------
NOMINAL_HARAKAT: Dict[str, float] = {
    # nasal / hum rules
    "ghunnah_mushaddadah": 2.0, "idgham_bi_ghunnah": 2.0,
    "ikhfaa": 2.0, "ikhfaa_shafawi": 2.0, "iqlab": 2.0, "idgham_shafawi": 2.0,
    # idgham without ghunnah / consonant-assimilation family: one beat's hold
    "idgham_bila_ghunnah": 1.0, "idgham_mutamathilayn": 1.0,
    "idgham_mutaqaribayn": 1.0, "idgham_mutajanisayn_kamil": 1.0,
    "idgham_mutajanisayn_naqis": 1.0,
    # qalqalah, in harakat-equivalent release duration
    "qalqala_sughra": 0.5, "qalqala_kubra": 1.0, "qalqala_akbar": 1.5,
    # madd system. muttasil/munfasil default to 4 (Hafs via Shatibiyyah also
    # permits 5 -- override via TajweedGrader(nominal_overrides=...) if your
    # target recitation convention uses 5).
    "madd_tabii": 2.0, "madd_muttasil": 4.0, "madd_munfasil": 4.0,
    "madd_lazim": 6.0,
    # 'arid lis-sukun and leen permit 2, 4, or 6 -- nominal is a baseline,
    # TOLERANCE below is deliberately wide to accept all three.
    "madd_arid_lissukun": 2.0, "madd_leen": 2.0,
    "madd_iwad": 2.0, "madd_badal": 2.0, "madd_silah": 2.0,
}

# Tolerance bands, as ratio of measured/nominal harakat. Wide on purpose: real
# qira'ah variation exists, and alignment has ~1 frame of boundary noise.
TOLERANCE: Dict[str, Tuple[float, float]] = {
    "madd_tabii": (0.65, 1.60),
    "madd_muttasil": (0.55, 1.55),      # covers both the 4- and 5-harakah convention
    "madd_munfasil": (0.55, 1.60),
    "madd_lazim": (0.75, 1.35),         # 6 harakat is obligatory, tighter band
    "madd_arid_lissukun": (0.45, 3.20), # 2, 4 or 6 all permitted -> very wide
    "madd_leen": (0.45, 3.20),
    "madd_iwad": (0.65, 1.70),
    "madd_badal": (0.65, 1.70),
    "madd_silah": (0.60, 1.75),
    "ghunnah_mushaddadah": (0.60, 1.80),
    "idgham_bi_ghunnah": (0.55, 1.90),
    "ikhfaa": (0.55, 1.90),
    "ikhfaa_shafawi": (0.55, 1.90),
    "iqlab": (0.55, 1.90),
    "idgham_shafawi": (0.55, 1.90),
    "idgham_bila_ghunnah": (0.45, 2.00),
    "idgham_mutamathilayn": (0.45, 2.00),
    "idgham_mutaqaribayn": (0.45, 2.00),
    "idgham_mutajanisayn_kamil": (0.45, 2.00),
    "idgham_mutajanisayn_naqis": (0.45, 2.00),
    "qalqala_sughra": (0.40, 2.40),
    "qalqala_kubra": (0.40, 2.40),
    "qalqala_akbar": (0.40, 2.40),
}
DEFAULT_TOLERANCE = (0.50, 2.00)

# Rules whose verdict is categorical (present / absent / quality) rather than
# durational: no NOMINAL_HARAKAT entry, so `_decide` falls back to the ML
# verifier alone for these.
CATEGORICAL = {
    "izhar", "izhar_shafawi", "lam_shamsiyyah", "lam_qamariyyah",
    "tafkheem", "tarqeeq", "imala", "tashil", "ishmam", "ibdal_hamza",
    "hamza_wasl_silent", "hamza_wasl_fatha", "hamza_wasl_kasra",
    "hamza_wasl_damma", "iltiqa_haraka", "iltiqa_shortening",
    "waqf_diacritic_drop", "waqf_silah_drop", "waqf_taa_marbuta",
    "pausal_alif", "orthographic_silence",
}

SEVERITY: Dict[str, str] = {
    "ghunnah_mushaddadah": "major", "idgham_bi_ghunnah": "major",
    "ikhfaa": "major", "ikhfaa_shafawi": "major", "iqlab": "major",
    "idgham_shafawi": "major", "idgham_mutamathilayn": "major",
    "idgham_mutaqaribayn": "major", "idgham_mutajanisayn_kamil": "major",
    "idgham_mutajanisayn_naqis": "major", "idgham_bila_ghunnah": "major",
    "madd_lazim": "major", "madd_muttasil": "major",
    "lam_shamsiyyah": "major", "lam_qamariyyah": "major",
    "tafkheem": "major", "tarqeeq": "major",
    "madd_munfasil": "minor", "madd_tabii": "minor",
    "madd_arid_lissukun": "minor", "madd_leen": "minor",
    "madd_iwad": "minor", "madd_badal": "minor", "madd_silah": "minor",
    "qalqala_sughra": "minor", "qalqala_kubra": "minor", "qalqala_akbar": "minor",
    "izhar": "minor", "izhar_shafawi": "minor",
}


@dataclass
class Verdict:
    rule: str
    human: str
    word_idx: int
    letters: str
    start_ms: float
    end_ms: float
    expected_harakat: float
    measured_harakat: float
    verdict: str
    confidence: float
    severity: str = "minor"
    message: str = ""


@dataclass
class Report:
    surah: int
    ayah: int
    harakah_ms: float
    token_accuracy: float
    verdicts: List[Verdict] = field(default_factory=list)

    @property
    def errors(self) -> List[Verdict]:
        return [v for v in self.verdicts if v.verdict != "correct"]

    @property
    def score(self) -> float:
        if not self.verdicts:
            return 0.0
        w = {"major": 3.0, "minor": 1.0}
        tot = sum(w[SEVERITY.get(v.rule, "minor")] for v in self.verdicts)
        lost = sum(w[SEVERITY.get(v.rule, "minor")] * v.confidence
                   for v in self.errors)
        return round(100.0 * max(0.0, 1.0 - lost / max(tot, 1e-6)), 1)


def estimate_harakah_ms(alignment: Sequence[Tuple[str, int, int]]) -> float:
    """
    The reciter's tempo unit: median duration of the short vowels a / i / u.
    Median, not mean -- one badly aligned vowel at an utterance edge can be
    10x too long and would drag a mean far enough to shift every verdict.
    """
    d = [(e - s) * FRAME_MS for (t, s, e) in alignment if t in ("a", "i", "u")]
    if len(d) < 3:
        return 180.0
    return float(np.median(d))


def span_bounds(alignment: Sequence[Tuple[str, int, int]],
                start: int, end: int) -> Optional[Tuple[float, float]]:
    seg = alignment[start:end]
    seg = [x for x in seg if x[2] > x[1]]
    if not seg:
        return None
    return seg[0][1] * FRAME_MS, seg[-1][2] * FRAME_MS


class TajweedGrader:
    def __init__(self, verifier_threshold: float = 0.60, report_minor: bool = True,
                 nominal_overrides: Optional[Dict[str, float]] = None,
                 tolerance_overrides: Optional[Dict[str, Tuple[float, float]]] = None):
        self.vt = verifier_threshold
        self.report_minor = report_minor
        self.nominal = {**NOMINAL_HARAKAT, **(nominal_overrides or {})}
        self.tolerance = {**TOLERANCE, **(tolerance_overrides or {})}

    def grade(self, surah: int, ayah: int,
              alignment: Sequence[Tuple[str, int, int]],
              spans: Sequence, verifier_probs: Optional[np.ndarray] = None,
              token_accuracy: float = 1.0) -> Report:
        h = estimate_harakah_ms(alignment)
        rep = Report(surah, ayah, h, token_accuracy)

        for i, sp in enumerate(spans):
            rule = sp.rule if hasattr(sp, "rule") else sp["rule"]
            start = sp.start if hasattr(sp, "start") else sp["start"]
            end = sp.end if hasattr(sp, "end") else sp["end"]
            letters = sp.letters if hasattr(sp, "letters") else sp.get("letters", "")
            word_idx = sp.word_idx if hasattr(sp, "word_idx") else sp.get("word_idx", 0)

            bounds = span_bounds(alignment, start, end)
            probs = verifier_probs[i] if verifier_probs is not None else None

            if bounds is None:
                rep.verdicts.append(self._mk(rule, letters, word_idx, 0.0, 0.0,
                                             0.0, "missing", 0.9))
                continue

            t0, t1 = bounds
            measured = (t1 - t0) / h
            expected = float(self.nominal.get(rule, 0.0))

            verdict, conf = self._decide(rule, measured, expected, probs)
            rep.verdicts.append(self._mk(rule, letters, word_idx, t0, t1,
                                         measured, verdict, conf, expected))
        if not self.report_minor:
            rep.verdicts = [v for v in rep.verdicts
                            if v.verdict == "correct" or v.severity == "major"]
        return rep

    def _decide(self, rule: str, measured: float, expected: float,
               probs: Optional[np.ndarray]) -> Tuple[str, float]:
        det_verdict, det_conf = "correct", 0.0
        if rule not in CATEGORICAL and expected > 0:
            lo, hi = self.tolerance.get(rule, DEFAULT_TOLERANCE)
            ratio = measured / expected
            if ratio < lo:
                det_verdict = "too_short"
                det_conf = min(1.0, (lo - ratio) / max(lo, 1e-6) * 1.8)
            elif ratio > hi:
                det_verdict = "too_long"
                det_conf = min(1.0, (ratio - hi) / max(hi, 1e-6) * 1.8)

        if probs is None:
            return det_verdict, round(det_conf, 2)
        k = int(np.argmax(probs))
        ml_verdict, ml_conf = CLASSES[k], float(probs[k])

        if ml_verdict == "correct" and det_verdict == "correct":
            return "correct", 0.0
        if ml_verdict != "correct" and det_verdict != "correct":
            if ml_verdict in ("no_ghunnah", "weak_articulation", "substituted"):
                return ml_verdict, round(min(0.99, 0.5 * ml_conf + 0.5 * det_conf + 0.2), 2)
            return det_verdict, round(min(0.99, 0.5 * ml_conf + 0.5 * det_conf + 0.2), 2)
        if ml_verdict != "correct":
            return (ml_verdict, round(ml_conf, 2)) if ml_conf >= self.vt else ("correct", 0.0)
        return (det_verdict, round(det_conf, 2)) if det_conf >= self.vt else ("correct", 0.0)

    def _mk(self, rule: str, letters: str, word_idx: int, t0: float, t1: float,
           measured: float, verdict: str, conf: float, expected: float = 0.0) -> Verdict:
        human = human_name(rule)
        sev = SEVERITY.get(rule, "minor")
        return Verdict(
            rule=rule, human=human, word_idx=word_idx, letters=letters,
            start_ms=round(t0, 1), end_ms=round(t1, 1),
            expected_harakat=expected, measured_harakat=round(measured, 2),
            verdict=verdict, confidence=conf, severity=sev,
            message=self._message(rule, human, verdict, measured, expected))

    @staticmethod
    def _message(rule: str, human: str, verdict: str,
                 measured: float, expected: float) -> str:
        if verdict == "correct":
            return f"{human}: correct"
        if verdict == "too_short":
            return (f"{human}: held for about {measured:.1f} harakat, "
                    f"should be {expected:.0f}. Lengthen it.")
        if verdict == "too_long":
            return (f"{human}: held for about {measured:.1f} harakat, "
                    f"should be {expected:.0f}. Shorten it.")
        if verdict == "missing":
            return f"{human}: not applied here."
        if verdict == "no_ghunnah":
            return (f"{human}: the nasal hum (ghunnah) is missing -- the sound "
                    f"should resonate through the nose for about 2 harakat.")
        if verdict == "substituted":
            return f"{human}: a different sound was produced than the rule requires."
        if verdict == "weak_articulation":
            return f"{human}: applied, but articulated too weakly to be clear."
        if verdict == "inserted":
            return f"{human}: applied where the rule does not call for it."
        return f"{human}: {verdict}"


def format_report(rep: Report, arabic_words: Optional[List[str]] = None) -> str:
    lines = [f"Ayah {rep.surah}:{rep.ayah}",
             f"  tempo          : {rep.harakah_ms:.0f} ms per harakah",
             f"  pronunciation  : {rep.token_accuracy*100:.1f}% of expected sounds matched",
             f"  tajweed score  : {rep.score}/100",
             f"  rules checked  : {len(rep.verdicts)}  |  issues: {len(rep.errors)}"]
    if rep.errors:
        lines.append("")
        for v in sorted(rep.errors, key=lambda x: x.start_ms):
            w = ""
            if arabic_words and 0 <= v.word_idx < len(arabic_words):
                w = f"  [{arabic_words[v.word_idx]}]"
            lines.append(f"  {v.start_ms/1000:6.2f}s  ({v.severity:<5}) "
                         f"{v.message}{w}")
    else:
        lines.append("\n  No tajweed issues detected. Ma sha Allah.")
    return "\n".join(lines)
